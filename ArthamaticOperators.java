public class ArthamaticOperators {
    public static void main(String[] args) {
        int a = 100;
        int b = 200;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println((float)a/b);
        System.out.println(a%b);
        System.out.println(a++);
        System.out.println(a--);
        System.out.println(++a);
        System.out.println(--a);
        int c=1000;
        c +=10;//c=c+10
        System.out.println(c);
    }
}
